function initDailyPage() {
    const textElement = document.getElementById('daily-text');
    const dateElement = document.getElementById('current-date');
    const bg = document.getElementById('bg-hearts');

    // 1. عرض التاريخ بشكل أنيق
    const now = new Date();
    const options = { weekday: 'long', day: 'numeric', month: 'long' };
    dateElement.textContent = now.toLocaleDateString('ar-EG', options);

    // 2. اختيار الرسالة حسب اليوم
    const start = new Date(now.getFullYear(), 0, 0);
    const diff = now - start;
    const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
    textElement.textContent = MESSAGES[dayOfYear % MESSAGES.length];

    // 3. توليد قلوب متطايرة في الخلفية
    for (let i = 0; i < 15; i++) {
        createFloatingHeart(bg);
    }
}

function createFloatingHeart(container) {
    const heart = document.createElement('div');
    heart.className = 'b-heart';
    heart.innerHTML = '❤️';
    heart.style.left = Math.random() * 100 + 'vw';
    heart.style.animationDuration = (Math.random() * 5 + 5) + 's';
    heart.style.opacity = Math.random();
    heart.style.fontSize = (Math.random() * 20 + 10) + 'px';
    
    container.appendChild(heart);
    
    // إعادة التوليد بعد انتهاء الحركة
    setTimeout(() => {
        heart.remove();
        createFloatingHeart(container);
    }, 10000);
}

document.addEventListener('DOMContentLoaded', initDailyPage);